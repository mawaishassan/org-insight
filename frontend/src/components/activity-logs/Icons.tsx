import React from "react";

export interface IconProps extends React.SVGProps<SVGSVGElement> {
  className?: string;
  size?: number | string;
}

function parseSize(className?: string, size?: number | string): number {
  if (typeof size === "number") return size;
  if (typeof size === "string" && !isNaN(Number(size))) return Number(size);
  if (!className) return 16;
  if (className.includes("w-8") || className.includes("h-8")) return 32;
  if (className.includes("w-7") || className.includes("h-7")) return 28;
  if (className.includes("w-6") || className.includes("h-6")) return 24;
  if (className.includes("w-5") || className.includes("h-5")) return 20;
  if (className.includes("w-4") || className.includes("h-4")) return 16;
  if (className.includes("w-3.5") || className.includes("h-3.5")) return 14;
  if (className.includes("w-3") || className.includes("h-3")) return 12;
  return 16;
}

const createIcon = (paths: React.ReactNode) => {
  const IconComponent: React.FC<IconProps> = ({ className, size, style, width, height, ...props }) => {
    const s = parseSize(className, size);
    const finalW = width || s;
    const finalH = height || s;
    return (
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        width={finalW}
        height={finalH}
        style={{
          width: finalW,
          height: finalH,
          display: "inline-block",
          verticalAlign: "middle",
          flexShrink: 0,
          ...style,
        }}
        {...props}
      >
        {paths}
      </svg>
    );
  };
  return IconComponent;
};

